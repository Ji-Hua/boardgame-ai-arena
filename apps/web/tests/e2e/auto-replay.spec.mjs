import {test,expect} from '@playwright/test'
test('paused replay automatically analyzes; playback stays quiet; seeks reuse cache',async({page},info)=>{
 const requests=[];const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('request',r=>{if(r.url().endsWith('/api/v1/lab/analyze'))requests.push(r.postDataJSON())})
 await page.goto('/games/049f457b806f4604720d%3A0?season=cnn-architecture-20261021-213018&agent=A-baseline_seed-44&opponent=greedy&ply=14')
 await expect(page.getByLabel('决策依据')).toContainText('当前代码复算')
 expect(requests).toHaveLength(1);expect(requests[0].algorithm).toBe('dqn')
 await page.getByLabel('播放速度').selectOption('4')
 await page.getByRole('button',{name:'播放回放',exact:true}).click()
 await page.waitForTimeout(1500)
 await expect(page.getByRole('button',{name:'暂停回放',exact:true})).toBeVisible()
 expect(requests).toHaveLength(1)
 await page.getByRole('button',{name:'暂停回放',exact:true}).click()
 await expect(page.getByLabel('决策依据')).toContainText('当前代码复算')
 expect(requests).toHaveLength(2)
 await page.getByLabel('跳转步数').fill('14')
 await expect(page.getByLabel('决策依据')).toContainText('当前代码复算')
 await page.waitForTimeout(500);expect(requests).toHaveLength(2)
 await page.getByLabel('跳转步数').fill('9')
 await page.getByLabel('跳转步数').fill('11')
 await page.getByLabel('跳转步数').fill('13')
 await expect(page.getByLabel('决策依据')).toContainText('当前代码复算')
 expect(requests).toHaveLength(3);expect(requests[2].algorithm).toBe('greedy')
 await page.getByRole('button',{name:'跳到结束'}).click()
 await page.waitForTimeout(500);expect(requests).toHaveLength(3)
 await page.screenshot({path:info.outputPath('automatic-replay.png'),fullPage:true})
 expect(errors).toEqual([])
})
