import {test,expect} from '@playwright/test'
test('Mr Jack real API, hidden observation, reload and replay',async({page,context})=>{
 const errors=[];page.on('pageerror',e=>errors.push(String(e)))
 await page.goto('/projects/jack/play')
 await page.getByRole('button',{name:'开始研究对局'}).click()
 await expect(page.getByRole('img',{name:'伦敦棋盘，格号与动作列表对应'})).toBeVisible()
 const url=page.url()
 expect(url).toContain('#token=')
 const watch=await page.getByRole('link',{name:'打开观战视图'}).getAttribute('href')
 const spectator=await context.newPage();await spectator.goto(watch)
 await expect(spectator.getByRole('img')).toBeVisible()
 await expect(spectator.getByRole('button',{name:'执行对手动作'})).toHaveCount(0)
 await page.getByRole('button',{name:/选择 /}).first().click()
 await page.reload()
 await expect(page.getByRole('img')).toBeVisible()
 await page.getByRole('button',{name:'查看本视角回放'}).click()
 await expect(page.getByRole('slider',{name:'研究回放进度'})).toBeVisible()
 await page.screenshot({path:process.env.E2E_RESULTS_DIR+'/mrjack-board.png',fullPage:true})
 expect(errors).toEqual([])
 await page.getByRole('button',{name:'返回当前对局'}).click()
 await page.getByRole('button',{name:'关闭对局'}).click()
 await expect(page.getByRole('button',{name:'开始研究对局'})).toBeVisible()
})
