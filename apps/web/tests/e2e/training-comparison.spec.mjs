import {test,expect} from '@playwright/test'
const season='cnn-architecture-20261021-213018'
const a='40f0edbd60314c7ab822b6dfbd8522ef',b='9c1b3ed4a5004b5c933bb4bf77b594fe'
const sha='0faaae51ded5b88ed5e0b3d8774a6e5de954bf30a5ec72e4d8007afe344a15fc'
test('real multi-run comparison, config differences and checkpoint to replay and Play',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/training?'+new URLSearchParams({season})+'&run='+a+'&run='+b)
 await expect(page.getByRole('heading',{name:'2 Runs 对比'})).toBeVisible()
 await expect(page.locator('.aw-training-chart svg path')).toHaveCount(2)
 await expect(page.getByLabel('对比横轴')).toHaveValue('gradient_updates')
 await expect(page.locator('.aw-training-chart')).toContainText('历史训练文件')
 await expect(page.getByRole('link',{name:'MLflow ↗'})).toHaveCount(2)
 await page.screenshot({path:info.outputPath('training-compare.png'),fullPage:true})
 await page.getByRole('tab',{name:'配置对比',exact:true}).click()
 await expect(page.locator('.aw-config-table tbody tr').first()).toBeVisible()
 await expect(page.getByLabel('仅差异')).toBeChecked()
 const differences=await page.locator('.aw-config-table tbody tr').count()
 await page.getByLabel('仅差异').uncheck()
 expect(await page.locator('.aw-config-table tbody tr').count()).toBeGreaterThan(differences)
 await page.screenshot({path:info.outputPath('config-compare.png'),fullPage:true})
 await page.getByRole('tab',{name:'Checkpoints',exact:true}).click()
 const checkpoint=page.getByRole('row').filter({has:page.locator('a[href*="'+sha+'"]')}).first()
 await expect(checkpoint).toContainText('12000')
 await checkpoint.getByRole('link',{name:'评测 / 回放 / 对战'}).click()
 await expect(page.getByRole('heading',{name:'Checkpoint',exact:true})).toBeVisible()
 await expect(page.getByText(sha,{exact:true})).toBeVisible()
 await page.getByLabel('Checkpoint 对手').selectOption('greedy')
 await expect(page.getByRole('link',{name:'回放',exact:true}).first()).toBeVisible()
 await page.screenshot({path:info.outputPath('checkpoint-evaluation.png'),fullPage:true})
 const checkpointUrl=page.url()
 await page.getByRole('link',{name:'回放',exact:true}).first().click()
 await expect(page.getByLabel('回放步数')).toBeVisible()
 await page.getByRole('tab',{name:'证据',exact:true}).click()
 const viewer=page.getByLabel('完整证据 JSON')
 const data=JSON.parse(await viewer.textContent())
 expect(data.replay.positions.length).toBe(data.replay.actions.length+1)
 expect(data.participants.some(p=>p.sha256===sha)).toBe(true)
 expect(data.evaluation.manifest_sha256).toBeTruthy()
 const body=await page.locator('.aw-inspector-body').boundingBox(),box=await viewer.boundingBox()
 expect(box.width/body.width).toBeGreaterThan(.95)
 expect(box.height/body.height).toBeGreaterThan(.8)
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'下载 JSON'}).click();expect((await download).suggestedFilename()).toContain('evidence.json')
 await viewer.evaluate(e=>e.scrollTop=e.scrollHeight)
 await expect(viewer).toBeVisible()
 await page.screenshot({path:info.outputPath('replay-evidence.png'),fullPage:true})
 await page.goto(checkpointUrl)
 await page.getByRole('link',{name:'发起对战',exact:true}).click()
 await expect(page.getByLabel('P1 对战方')).toHaveValue('C-resnet_seed-42')
 await expect(page.getByLabel('P1 身份')).toContainText(sha.slice(0,12))
 await page.getByRole('button',{name:'开始对局',exact:true}).click()
 await expect(page.locator('.aw-play-inspector').getByText(sha,{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'关闭对局',exact:true}).click()
 expect(errors).toEqual([])
})
test('Run selections survive refresh; evidence and comparison fit mobile',async({page},info)=>{
 await page.goto('/training?season='+season+'&run='+a+'&run='+b)
 await expect(page.locator('.aw-training-chart svg path')).toHaveCount(2)
 await page.reload()
 await expect(page.getByLabel('选择 C-resnet_seed-42',{exact:true})).toBeChecked()
 await expect(page.getByLabel('选择 C-resnet_seed-43',{exact:true})).toBeChecked()
 await page.getByRole('tab',{name:'证据',exact:true}).click()
 await expect(page.getByLabel('完整证据 JSON')).toContainText('policy_cross_entropy')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('training-evidence-mobile.png'),fullPage:true})
 await page.getByRole('tab',{name:'配置对比',exact:true}).click()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByLabel('选择 C-resnet_seed-43',{exact:true}).uncheck()
 await expect(page.getByRole('heading',{name:'C-resnet_seed-42',exact:true})).toBeVisible()
})
