import {test,expect} from '@playwright/test'
const season='cnn-architecture-20261021-213018'
test('compact Agent detail links opponents, config, training and replay',async({page},info)=>{
 await page.goto('/agents/minimax_d2?season='+season)
 await expect(page.getByRole('link',{name:'回放',exact:true}).first()).toBeVisible()
 expect((await page.locator('.aw-agent-desk').boundingBox()).height).toBeLessThanOrEqual(740)
 await page.getByLabel('筛选对手').fill('C-resnet_seed-42')
 await expect(page.locator('.aw-opponent')).toHaveCount(1)
 await page.locator('.aw-opponent').click()
 await expect(page.locator('.aw-agent-content h2')).toContainText('C-resnet')
 await expect(page.getByRole('link',{name:'回放',exact:true}).first()).toBeVisible()
 await page.getByLabel('筛选对手').fill('')
 await page.screenshot({path:info.outputPath('compact-matches.png'),fullPage:true})
 await page.getByRole('tab',{name:'配置',exact:true}).click()
 await expect(page.getByRole('heading',{name:'搜索 / 策略配置'})).toBeVisible()
 await page.reload();await expect(page.getByRole('tab',{name:'配置',exact:true})).toHaveAttribute('aria-selected','true')
 await page.getByRole('tab',{name:'训练记录',exact:true}).click()
 await expect(page.getByText('该类型无需训练')).toBeVisible()
 await page.getByRole('tab',{name:'交手记录',exact:true}).click()
 await page.getByRole('link',{name:'回放',exact:true}).first().click()
 await expect(page.getByLabel('跳转步数')).toBeVisible()
 await page.goto('/agents/C-resnet_seed-42?season='+season+'&panel=training')
 await expect(page.locator('.aw-run-inspector')).toBeVisible()
 await expect(page.getByRole('link',{name:'打开训练工作区 / 添加 Run 对比'})).toBeVisible()
 await page.screenshot({path:info.outputPath('compact-training.png'),fullPage:true})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('compact-mobile.png'),fullPage:true})
})
