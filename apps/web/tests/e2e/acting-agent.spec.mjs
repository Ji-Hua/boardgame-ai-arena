import {test,expect} from '@playwright/test'
const season='cnn-architecture-20261021-213018'
const replay='/games/049f457b806f4604720d%3A0?'+new URLSearchParams({season,agent:'A-baseline_seed-44',opponent:'greedy',ply:'14'})
test('acting Agent follows each ply; actual decision, contrast, neural formatting and themes',async({page,request},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const data=await (await request.get('/api/agents/seasons/'+season+'/replay/049f457b806f4604720d%3A0')).json()
 const roster=await (await request.get('/api/agents/seasons/'+season)).json()
 await page.addInitScript(()=>localStorage.setItem('quoridor-workbench-theme','light'))
 await page.goto(replay)
 await expect(page.getByRole('button',{name:'当前 Agent',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByLabel('分析 Agent')).toHaveCount(0)
 const actor=roster.agents.find(a=>a.id===data[data.positions[14].turn===1?'p1':'p2'])
 await expect(page.locator('.aw-actor-context')).toContainText(actor.name)
 const pending=page.waitForRequest(r=>r.url().endsWith('/api/analyze'))
 await page.getByRole('button',{name:'运行分析',exact:true}).click()
 expect((await pending).postDataJSON().model_id).toBe(actor.sha256)
 await expect(page.getByLabel('决策依据')).toContainText('历史实际动作')
 await expect(page.getByLabel('决策依据')).toContainText('当前代码复算')
 await expect(page.locator('.aw-actual-row')).toBeVisible()
 await page.screenshot({path:info.outputPath('decision-light.png'),fullPage:true})
 await page.getByRole('tab',{name:'神经网络诊断',exact:true}).click()
 await page.getByRole('button',{name:'读取激活',exact:true}).click()
 const tensor=page.locator('.lab-tensor');await expect(tensor.locator('svg')).toBeVisible()
 const values=await tensor.locator('svg text').allTextContents()
 expect(values.every(v=>v.length<=9)).toBe(true)
 const full=await tensor.locator('svg title').first().textContent();expect(full).toMatch(/\[\d+,\d+\]:/)
 await tensor.getByLabel('显示数值').uncheck();await expect(tensor.locator('svg text')).toHaveCount(0)
 await tensor.getByLabel('显示数值').check()
 await page.getByRole('button',{name:'深色',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
 await page.screenshot({path:info.outputPath('tensor-dark.png'),fullPage:true})
 await page.getByRole('button',{name:'下一步',exact:true}).click()
 const next=roster.agents.find(a=>a.id===data[data.positions[15].turn===1?'p1':'p2'])
 await expect(page.locator('.aw-actor-context')).toContainText(next.name)
 await expect(page.getByText('当前局面未分析')).toBeVisible()
 await page.getByRole('button',{name:'运行分析',exact:true}).click()
 await expect(page.getByLabel('决策依据')).toContainText('对手路径增量 − 自身路径增量')
 await page.getByRole('button',{name:'对照分析',exact:true}).click()
 await page.getByLabel('分析 Agent').selectOption(actor.id)
 await page.getByRole('button',{name:'运行分析',exact:true}).click()
 await expect(page.getByLabel('决策依据')).toContainText('对照复算')
 await page.getByRole('button',{name:'当前 Agent',exact:true}).click()
 await expect(page.locator('.aw-actor-context')).toContainText(next.name)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('decision-mobile.png'),fullPage:true})
 expect(errors).toEqual([])
})
