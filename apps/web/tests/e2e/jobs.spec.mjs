import {test,expect} from '@playwright/test'
// Real GPU Job through the UI. Needs E2E_PLATFORM_TOKEN; registers small smoke checkpoints into catalog-jobs.json.
const token=process.env.E2E_PLATFORM_TOKEN
test('submit a templated GPU training Job, follow it live and open its registered model and run',async({page},info)=>{
 test.skip(!token,'E2E_PLATFORM_TOKEN is required for Job writes')
 test.setTimeout(600_000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/jobs')
 await expect(page.getByText(/GeForce RTX 3080 Ti/)).toBeVisible()
 await page.getByRole('link',{name:'新建任务'}).click()
 await page.getByLabel('配置模板').selectOption('platform_job_smoke.yaml')
 await expect(page.getByLabel('任务配置')).toHaveValue(/episodes: 40/)
 await page.getByLabel('任务名称').fill('ui-smoke')
 await page.getByLabel('所属实验').fill('platform-jobs-acceptance')
 await page.getByLabel('写入令牌').fill(token)
 await page.getByRole('button',{name:'提交任务'}).click()
 await expect(page.getByRole('heading',{name:'ui-smoke'})).toBeVisible()
 await page.screenshot({path:info.outputPath('job-running.png'),fullPage:true})
 await expect(page.getByText('已完成',{exact:true})).toBeVisible({timeout:540_000})
 await expect(page.locator('.chart-card')).toBeVisible()
 await page.getByRole('tab',{name:/评测/}).click()
 await expect(page.getByRole('cell',{name:'greedy'}).first()).toBeVisible()
 await page.getByRole('tab',{name:'日志'}).click()
 await expect(page.locator('.pf-log')).toContainText('device=cuda')
 await page.screenshot({path:info.outputPath('job-done.png'),fullPage:true})
 const model=page.getByRole('link',{name:/^模型 /}).last()
 const href=await model.getAttribute('href')
 await page.getByRole('link',{name:'在训练工作区查看'}).click()
 await expect(page.locator('.aw-run-choice.aw-selected')).toBeVisible()
 await expect(page.locator('.chart-card').first()).toBeVisible()
 await page.goto(href)
 await expect(page.locator('.aw-hash').first()).toHaveText(href.split('/').pop())
 await page.getByRole('tab',{name:/训练来源/}).click()
 await expect(page.getByRole('row').filter({hasText:'legacy'}).first()).toBeVisible()
 expect(errors).toEqual([])
})
