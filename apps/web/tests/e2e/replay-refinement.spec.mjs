import {test,expect} from '@playwright/test'
const season='cnn-architecture-20261021-213018'
const replay='/games/049f457b806f4604720d%3A0?'+new URLSearchParams({season,agent:'A-baseline_seed-44',opponent:'greedy',ply:'13'})
test('replay transport, analyst persistence, compact panels and responsive layout',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto(replay)
 await expect(page.getByLabel('跳转步数')).toHaveValue('13')
 await expect(page.getByLabel('P1 身份')).toContainText('A-baseline')
 await expect(page.getByLabel('P2 身份')).toContainText('Greedy')
 await page.getByRole('button',{name:'对照分析',exact:true}).click()
 await page.getByLabel('分析 Agent').selectOption('minimax_d1')
 await page.getByRole('button',{name:'回到开头'}).click()
 await expect(page.getByLabel('跳转步数')).toHaveValue('0')
 await page.getByLabel('播放速度').selectOption('4')
 await page.getByRole('button',{name:'播放回放',exact:true}).click()
 await expect(page.getByLabel('跳转步数')).not.toHaveValue('0')
 await page.getByRole('button',{name:'暂停回放',exact:true}).click()
 const paused=await page.getByLabel('跳转步数').inputValue()
 await page.waitForTimeout(500)
 await expect(page.getByLabel('跳转步数')).toHaveValue(paused)
 await page.getByRole('button',{name:'跳到结束'}).click()
 await expect(page.getByRole('button',{name:'下一步',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'回到开头'}).click()
 await expect(page.getByLabel('分析 Agent')).toHaveValue('minimax_d1')
 await page.getByLabel('跳转步数').fill('13')
 await page.reload()
 await expect(page.getByLabel('跳转步数')).toHaveValue('13')
 await page.getByRole('button',{name:'对照分析',exact:true}).click()
 await page.getByLabel('分析 Agent').selectOption('minimax_d1')
 await page.getByRole('button',{name:'运行分析',exact:true}).click()
 await expect(page.getByRole('button',{name:'变化',exact:true}).first()).toBeVisible()
 expect(await page.getByRole('button',{name:'变化',exact:true}).count()).toBeLessThanOrEqual(11)
 await page.getByRole('button',{name:'变化',exact:true}).first().click()
 await expect(page.getByText('候选分支',{exact:false}).first()).toBeVisible()
 await page.getByRole('tab',{name:'搜索',exact:true}).click()
 await expect(page.getByRole('heading',{name:'主变化'})).toBeVisible()
 await expect(page.locator('.aw-analysis .aw-moves button').first()).toBeEnabled()
 await page.locator('.aw-analysis .aw-moves button').first().click()
 await page.getByRole('button',{name:'返回原局面'}).last().click()
 await page.getByRole('tab',{name:'棋谱',exact:true}).click()
 await page.locator('.aw-move-list button').nth(8).click()
 await expect(page.getByLabel('跳转步数')).toHaveValue('8')
 await page.getByRole('tab',{name:'逐步分析',exact:true}).click()
 await expect(page.getByText('当前局面未分析')).toBeVisible()
 const inspector=await page.locator('.aw-inspector').boundingBox()
 expect(inspector.height).toBeLessThanOrEqual(760)
 await page.screenshot({path:info.outputPath('replay-desktop.png'),fullPage:true})
 await page.setViewportSize({width:1366,height:768})
 const transport=await page.getByRole('button',{name:'播放回放',exact:true}).boundingBox()
 expect(transport.y+transport.height).toBeLessThan(768)
 await page.screenshot({path:info.outputPath('replay-short-desktop.png'),fullPage:true})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('replay-mobile.png'),fullPage:true})
 expect(errors).toEqual([])
})
test('Agent-origin play clearly labels both seats and allows swap',async({page},info)=>{
 await page.goto('/agents/A-baseline_seed-44?season='+season)
 await page.getByRole('link',{name:'发起对战',exact:true}).click()
 await expect(page.getByLabel('P1 身份')).toContainText('A-baseline')
 await expect(page.getByLabel('P1 身份')).toContainText('神经网络')
 await expect(page.getByLabel('P2 身份')).toContainText('你控制此方')
 await page.getByRole('button',{name:'交换先后手',exact:true}).click()
 await expect(page.getByLabel('P1 身份')).toContainText('你控制此方')
 await expect(page.getByLabel('P2 身份')).toContainText('A-baseline')
 await page.screenshot({path:info.outputPath('play-seats.png'),fullPage:true})
})
